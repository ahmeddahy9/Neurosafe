"""Download a documented sample of FAERS reports through the openFDA API.

Strategy: for every study drug and every calendar quarter in the chosen date
window, request up to ``--cap`` reports (openFDA hard limit: 1000 per request).
The API also reports how many reports match each window; that total is stored
so the dashboard can show sample size vs. true matches.

Examples
--------
python scripts/download_data.py                       # defaults from src/config.py / .env
python scripts/download_data.py --start 2025-01-01 --cap 200
python scripts/download_data.py --dry-run             # print the queries only
python scripts/download_data.py --use-sample          # SYNTHETIC offline data, UI testing only
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import requests  # noqa: E402

from src import config, data_loader  # noqa: E402


def use_sample() -> int:
    from make_sample_data import generate

    if not config.SAMPLE_FILE.exists():
        generate(config.SAMPLE_FILE)
    config.RAW_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(config.SAMPLE_FILE, config.RAW_FILE)
    n = sum(1 for _ in config.RAW_FILE.open(encoding="utf-8"))
    data_loader.write_json(config.RAW_META_FILE, {
        "is_sample": True,
        "source": "SYNTHETIC sample generated by scripts/make_sample_data.py",
        "warning": "Random test records. NOT FAERS data. For UI/pipeline testing only.",
        "download_date_utc": data_loader.now_utc_iso(),
        "n_records": n,
        "drugs": config.SEDATIVE_DRUGS,
    })
    print(f"[sample] Copied {n} SYNTHETIC records to {config.RAW_FILE}")
    print("[sample] REMINDER: this is not real data; the dashboard will show a red banner.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--start", default=config.START_DATE, help="first receive date, YYYY-MM-DD")
    ap.add_argument("--end", default=config.END_DATE, help="last receive date, YYYY-MM-DD")
    ap.add_argument("--cap", type=int, default=config.MAX_REPORTS_PER_DRUG_WINDOW,
                    help="max reports per drug and quarter (<= 1000)")
    ap.add_argument("--drugs", nargs="*", default=None, help="override config.SEDATIVE_DRUGS")
    ap.add_argument("--dry-run", action="store_true", help="print queries without calling the API")
    ap.add_argument("--use-sample", action="store_true", help="use the SYNTHETIC offline sample instead")
    args = ap.parse_args()

    if args.use_sample:
        return use_sample()

    drugs = [d.upper() for d in (args.drugs or config.SEDATIVE_DRUGS)]
    windows = data_loader.quarter_windows(args.start, args.end)
    print(f"Drugs: {drugs}\nWindows: {len(windows)} quarters ({windows[0][0]} .. {windows[-1][1]}), cap {args.cap}/window")

    if args.dry_run:
        for drug in drugs:
            for s, e in windows[:2]:
                print(" ", data_loader.build_search_query(drug, s, e))
        print("  ... (dry run, nothing downloaded)")
        return 0

    session = requests.Session()
    session.headers["User-Agent"] = "NeuroSafe-educational-project/1.0"
    reports: dict[str, dict] = {}
    window_log, failures, api_updated = [], [], None

    for drug in drugs:
        for s, e in windows:
            try:
                recs, total, updated = data_loader.fetch_window(session, drug, s, e, limit=args.cap)
            except data_loader.DownloadError as exc:
                failures.append(str(exc))
                print(f"  ! {drug} {s}..{e}: {exc}")
                continue
            api_updated = updated or api_updated
            for rec in recs:
                rid = str(rec.get("safetyreportid"))
                kept = reports.setdefault(rid, data_loader.trim_record(rec))
                kept.setdefault("_queried_drugs", [])
                if drug not in kept["_queried_drugs"]:
                    kept["_queried_drugs"].append(drug)
            window_log.append({"drug": drug, "window_start": str(s), "window_end": str(e),
                               "api_total_matches": total, "fetched": len(recs)})
            print(f"  {drug:<16} {s}..{e}  matches={total:<6} fetched={len(recs)}")

    if not reports:
        print("\nNo data downloaded. If your network blocks api.fda.gov, run:\n"
              "  python scripts/download_data.py --use-sample   (SYNTHETIC, UI testing only)")
        return 1

    config.RAW_DIR.mkdir(parents=True, exist_ok=True)
    with config.RAW_FILE.open("w", encoding="utf-8") as fh:
        for rec in reports.values():
            fh.write(json.dumps(rec) + "\n")

    data_loader.write_json(config.RAW_META_FILE, {
        "is_sample": False,
        "source": "FDA FAERS via openFDA Drug Adverse Event API",
        "source_url": config.OPENFDA_DOCS_URL,
        "endpoint": config.OPENFDA_ENDPOINT,
        "license": "CC0 1.0 Universal (public domain dedication) per openFDA; see " + config.OPENFDA_LICENSE_URL,
        "terms_url": config.OPENFDA_TERMS_URL,
        "download_date_utc": data_loader.now_utc_iso(),
        "api_last_updated": api_updated,
        "date_window": [args.start, args.end],
        "cap_per_drug_window": args.cap,
        "drugs": drugs,
        "query_template": data_loader.build_search_query("<DRUG>", windows[0][0], windows[0][1]),
        "n_unique_reports_downloaded": len(reports),
        "n_failed_windows": len(failures),
        "failures": failures[:20],
        "windows": window_log,
        "note": "Capped, non-random sample: per-drug counts are NOT population volumes. "
                "`api_total_matches` is the number of matching reports reported by the API.",
    })
    print(f"\nSaved {len(reports)} unique reports -> {config.RAW_FILE}")
    if failures:
        print(f"WARNING: {len(failures)} window(s) failed; re-run to retry.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
